export function credit(n: number): string {
  const alphabet = '0123456789ABCDEFGHJKLMNPQRTUWXY';
  const body = `91440300MA5D${String(10000 + n)}`;
  const code = `${body}${alphabet[n % alphabet.length]}`;
  if (!/^[0-9A-Z]{18}$/.test(code)) throw new Error(`bad credit ${code}`);
  return code;
}

